export const translations = { en, ar };

interface I18nContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof Translations) => string;
  isRTL: boolean;
  fonts: {
    regular: string;
    medium: string;
    semiBold: string;
    bold: string;
  };
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const deviceLanguage = getLocales()[0]?.languageCode === 'ar' ? 'ar' : 'en';
  const [language, setLanguageState] = useState<Language>(deviceLanguage);
  const userSelectionVersion = useRef(0);

  useEffect(() => {
    let active = true;
    const selectionVersionAtStart = userSelectionVersion.current;
    void hydrateLanguagePreference({
      readStoredLanguage: () => AsyncStorage.getItem('@viewstate_language'),
      selectionVersionAtStart,
      getSelectionVersion: () => userSelectionVersion.current,
      isActive: () => active,
      applyLanguage: setLanguageState,
      onReadError: console.error,
    });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback((lang: Language) => {
    userSelectionVersion.current += 1;
    setLanguageState(lang);
    AsyncStorage.setItem('@viewstate_language', lang).catch(console.error);
  }, []);

  const t = (key: keyof Translations): string => {
    const dict = translations[language];
    return (dict[key] || translations.en[key] || key) as string;
  };

  const isRTL = language === 'ar';

  const fonts = useMemo(() => ({
    regular: language === 'ar' ? 'Tajawal_400Regular' : 'Inter_400Regular',
    medium: language === 'ar' ? 'Tajawal_500Medium' : 'Inter_500Medium',
    semiBold: language === 'ar' ? 'Tajawal_700Bold' : 'Inter_600SemiBold', // Tajawal doesn't have 600, using 700 as fallback
    bold: language === 'ar' ? 'Tajawal_700Bold' : 'Inter_700Bold',
  }), [language]);

  const value = useMemo(() => ({ language, setLanguage, t, isRTL, fonts }), [language, isRTL, fonts]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
}
